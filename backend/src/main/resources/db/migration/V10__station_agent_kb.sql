CREATE TABLE IF NOT EXISTS kb_entries (
  id        BIGINT PRIMARY KEY AUTO_INCREMENT,
  doc       VARCHAR(128) NOT NULL COMMENT '文档名',
  section   VARCHAR(32)  NULL     COMMENT '条目号，如 第3条',
  title     VARCHAR(255) NOT NULL COMMENT '条目标题',
  content   TEXT         NOT NULL COMMENT '条目正文',
  tags      VARCHAR(255) NULL     COMMENT '检索关键词（空格分隔）',
  source    VARCHAR(255) NULL     COMMENT '依据来源',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  KEY idx_kb_doc (doc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE ai_logs
